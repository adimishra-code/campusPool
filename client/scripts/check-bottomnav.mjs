import puppeteer from "puppeteer-core";
const CHROME = "C:\\Program Files\\Google\\Chrome\\Application\\chrome.exe";
const b = await puppeteer.launch({ executablePath: CHROME, headless: "new", args: ["--no-sandbox"] });
const ctx = await b.createBrowserContext();
const p = await ctx.newPage();
await p.setViewport({ width: 390, height: 844 });
await p.goto("http://localhost:5173/login", { waitUntil: "domcontentloaded" });
await p.waitForSelector("input[type=email]");
await p.type("input[type=email]", "aarav@univ.edu");
await p.type("input[type=password]", "password123");
await Promise.all([p.waitForFunction(() => location.pathname.startsWith("/feed"), { timeout: 15000 }), p.click("button[type=submit]")]);
await new Promise((r) => setTimeout(r, 1500));
const info = await p.evaluate(() => {
  const n = document.querySelector(".bottom-nav");
  if (!n) return { exists: false };
  const cs = getComputedStyle(n);
  const r = n.getBoundingClientRect();
  const tabs = [...document.querySelectorAll(".bottom-tab")].map((t) => t.textContent.trim());
  return { exists: true, display: cs.display, position: cs.position, bottom: Math.round(r.bottom), top: Math.round(r.top), width: Math.round(r.width), tabs, hasFab: !!document.querySelector(".bottom-tab.fab") };
});
console.log(JSON.stringify(info, null, 2));
await p.screenshot({ path: "scripts/shots/phase2/feed-phone-viewport.png", fullPage: false });
await ctx.close();
await b.close();
