import puppeteer from "puppeteer-core";
const CHROME = "C:\Program Files\Google\Chrome\Application\chrome.exe";
const b = await puppeteer.launch({ executablePath: CHROME, headless: "new", args: ["--no-sandbox"] });
const p = await b.newPage();
p.on("console", (m) => console.log("CONSOLE:", m.type(), m.text()));
p.on("pageerror", (e) => console.log("PAGEERROR:", e.message));
p.on("requestfailed", (r) => console.log("REQFAIL:", r.url(), r.failure()?.errorText));
await p.goto("http://localhost:5173/login", { waitUntil: "networkidle2" });
await new Promise((r) => setTimeout(r, 3000));
console.log("ROOT HTML LEN:", await p.evaluate(() => document.getElementById("root")?.innerHTML.length ?? "no root"));
await b.close();
