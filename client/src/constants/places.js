// Alias for backward compatibility
export const CAMPUS_PLACES = GBU_PLACES;

export const CATEGORY_LABELS = {
  inside_gbu: "🎓 Inside GBU Campus",
  metro_transit: "🚇 Metro & Transit Hubs",
  markets_hubs: "🛍️ Markets & Student Hubs"
};

export function placeById(id) {
  return GBU_PLACES.find((p) => p.id === id) || null;
}

export function placeByAddress(address) {
  if (!address) return null;
  return (
    GBU_PLACES.find(
      (p) =>
        p.address.toLowerCase() === address.toLowerCase() ||
        p.label.toLowerCase() === address.toLowerCase()
    ) || null
  );
}

// Check if a place or address is inside GBU campus or an approved campus anchor
export function isCampusAnchor(placeOrAddress) {
  if (!placeOrAddress) return false;
  if (typeof placeOrAddress === "string") {
    const text = placeOrAddress.toLowerCase();
    if (text.includes("gautam buddha") || text.includes("gbu")) return true;
    const found = placeByAddress(placeOrAddress);
    return Boolean(found?.isCampus);
  }
  return Boolean(placeOrAddress.isCampus || placeOrAddress.category === "inside_gbu");
}

// Build GeoJSON location object expected by backend
export function toLocation(place) {
  if (!place) {
    return {
      address: "Main Gate 1, Gautam Buddha University, Greater Noida",
      coordinates: { type: "Point", coordinates: GBU_CENTER }
    };
  }

  // Handle custom typed places
  if (place.isCustom) {
    return {
      address: place.address || place.label || "Custom Location",
      coordinates: {
        type: "Point",
        coordinates: place.coordinates || GBU_CENTER
      }
    };
  }

  return {
    address: place.address || place.label,
    coordinates: {
      type: "Point",
      coordinates: place.coordinates || GBU_CENTER
    }
  };
}
